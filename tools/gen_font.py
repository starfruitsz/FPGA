# 字形编码表：0-9 数字, 10-15 A-F, 其余按需
CODE = {}
for i, ch in enumerate('0123456789ABCDEF'): CODE[ch] = i
CODE.update({'G':16,'H':17,'I':18,'L':19,'N':23,'O':24,'P':25,'R':27,'S':28,
             'T':29,'U':30,'V':31,'W':32,'X':33,'Y':34,'Z':35,'=':36,' ':37,
             ':':38,'.':39,'-':40,'?':41})

def glyph_hex(ch):
    rows = G.get(ch, G[' '])
    out = 0
    for i in range(8):
        pat = rows[i] if i < 7 else "     "
        bits = 0
        for j, c in enumerate(pat):
            if c == '#':
                bits |= (1 << (6 - j))   # x=1..5 -> bit6..bit2
        out = (out << 8) | (bits & 0xFF)
    return out

lines = []
for ch in sorted(CODE, key=lambda c: CODE[c]):
    lines.append("        6'd%-2d: glyph = 64'h%016X; // '%s'" % (CODE[ch], glyph_hex(ch), ch))
print("// ==== font case entries (%d) ====" % len(lines))
print("\n".join(lines))

# 文本模板：2 行 × 32 列
ROW0 = "AD=####  U=####  TB=####   "   # 25 chars + padding
ROW1 = "SCOPE V1.0 640X480 RUN     "
rows = [ROW0.ljust(32), ROW1.ljust(32)]
case_lines = []
for r in range(2):
    for c in range(32):
        ch = rows[r][c]
        code = CODE.get(ch, 37)
        case_lines.append("        7'd%-3d: code = 6'd%-2d; // '%s'" % (r*32 + c, code, ch))
print("\n// ==== template case entries ====")
print("\n".join(case_lines))
