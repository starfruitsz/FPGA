"""复现 RTL 渲染结果(含特性2 测量行), 生成 640x480 预览图"""
import math
from PIL import Image, ImageDraw

W, H, PLOT_H, AXIS_Y = 640, 480, 448, 224
BG, GRID, AXIS = (0, 17, 34), (17, 85, 17), (34, 170, 34)
CH0C, CH1C, TXT, TRIGC = (17, 255, 17), (255, 255, 17), (255, 255, 255), (255, 68, 68)

img = Image.new("RGB", (W, H), BG)
d = ImageDraw.Draw(img)

for x in range(0, W, 64): d.line([(x, 0), (x, PLOT_H-1)], fill=GRID)
for y in range(0, PLOT_H, 64): d.line([(0, y), (W-1, y)], fill=GRID)
d.line([(0, AXIS_Y), (W-1, AXIS_Y)], fill=AXIS)

# 触发电平线(红色虚线) 演示特性1
for x in range(0, W, 16):
    d.line([(x, 160), (x+8, 160)], fill=TRIGC)

ch0, ch1, prev = [], [], 512
for x in range(W):
    v = 512 + int(300 * math.sin(2 * math.pi * x / 200))
    ch0.append(max(0, min(1023, v)))
    prev = prev + (v - prev) // 12
    ch1.append(max(0, min(1023, prev)))

def y_of(s): return (PLOT_H - 1) - ((s * 7) >> 4)
def draw(ch, color):
    for x in range(1, W):
        y0, y1 = y_of(ch[x]), y_of(ch[x-1])
        d.line([(x, min(y0, y1)), (x, max(y0, y1))], fill=color)
draw(ch0, CH0C)
draw(ch1, CH1C)

