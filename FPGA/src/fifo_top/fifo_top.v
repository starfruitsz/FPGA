//------------------------------------------------------------------------------
// [明文接口] fifo_top: 异步 FIFO 顶层
//   Data[9:0] : 写数据(10bit)
//   WrClk/RdClk: 写/读时钟(可异步)
//   WrEn/RdEn : 写/读使能
//   Q[9:0]    : 读数据(FWFT 模式下读使能有效即出数)
//   Empty/Full: 空/满标志
// 内部: 例化加密模块 \~fifo.fifo_top(即 fifo.v 中的实现), 并驱动 VCC/GND/GSR
//       三个全局原语(GSR 为全局复位网络, GSRI=VCC 表示不复位)。
//------------------------------------------------------------------------------
module fifo_top (
  Data,
  WrClk,
  RdClk,
  WrEn,
  RdEn,
  Q,
  Empty,
  Full
)
;
input [9:0] Data;
input WrClk;
input RdClk;
input WrEn;
input RdEn;
output [9:0] Q;
output Empty;
output Full;
wire VCC;
wire GND;
  \~fifo.fifo_top  fifo_inst (
    .RdClk(RdClk),
    .WrClk(WrClk),
    .WrEn(WrEn),
    .RdEn(RdEn),
    .Data(Data[9:0]),
    .Full(Full),
    .Empty(Empty),
    .Q(Q[9:0])
);
  VCC VCC_cZ (
    .V(VCC)
);
  GND GND_cZ (
    .G(GND)
);
  GSR GSR (
    .GSRI(VCC) 
);
//------------------------------------------------------------------------------
// 说明: endmodule 之后无其他逻辑; 若要在设计中使用, 请参考 fifo_top_tmp.v
// 中的例化模板, 并注意读写时钟域与使能的握手。
//------------------------------------------------------------------------------
endmodule /* fifo_top */
