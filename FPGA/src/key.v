//==============================================================================
// 文件: key.v            模块: key            实例名: key_inst(adda 顶层)
// 功能: 机械按键消抖(20ms)并输出稳定的按键电平。
//   输入 key_in = 1 表示松开, 0 表示按下(低有效按键)。
//   未按下时计数器清零; 持续按下满 20ms 后 key_out 翻转一次并锁存。
//   因此 key_out 是'按一次变一次'的翻转式状态, 而不是电平跟随。
// 时钟: sys_clk = 50MHz
//==============================================================================
module key 
( 
    input wire key_in, 
    input wire sys_clk, 
    input wire sys_rst_n, 
 
    output reg key_out 
); 
    
//------------------------------------------------------------------------------
// 内部信号: cnt_20ms 为 20ms 消抖计数器(0~999999)
//------------------------------------------------------------------------------
reg [19:0] cnt_20ms; 

//------------------------------------------------------------------------------
// 参数: CNT_MAX = 999999, 50MHz 下 (999999+1)/50MHz = 20ms
//------------------------------------------------------------------------------
parameter CNT_MAX=20'd999_999; 

//------------------------------------------------------------------------------
// [块 1] 消抖计时
//   key_in=1(松开)      : 计数清零, 重新计时
//   按下且已计满 20ms   : 保持计数值(避免溢出)
//   按下但未满 20ms     : 继续 +1
// 由于松开即清零, 抖动期间的短脉冲无法计满 20ms, 从而实现消抖。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        cnt_20ms<=20'd0; 
    else if(key_in==1'b1) //没按下保持 0 
        cnt_20ms<=20'd0; 
    else if(key_in==1'b0 && cnt_20ms==CNT_MAX) //非抖动确定按下，保持计数值 
        cnt_20ms<=cnt_20ms; 
    else 
        cnt_20ms<=cnt_20ms+1'b1; //按下后计数 20ms 
 
//------------------------------------------------------------------------------
// [块 2] 翻转输出
// 计到 CNT_MAX-1 的那一拍翻转 key_out(此时已稳定按下约 20ms)。
// 注意: 计满后计数值保持在 CNT_MAX(块 1), 不会再次触发, 保证按一次只翻转一次。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n == 1'b0) 
        key_out <= 1'b1; 
    else if(cnt_20ms == CNT_MAX - 1'b1) 
        key_out <= ~key_out; 
    else 
        key_out <= key_out; 
 
//------------------------------------------------------------------------------
// 用法: adda 中用 key_out==0 判断'按键状态', 从而在两种 DA 输出之间切换。
//------------------------------------------------------------------------------
endmodule 