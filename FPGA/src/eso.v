//==============================================================================
// 文件: eso.v            模块: eso            实例名: eso_inst(adda 顶层)
// 功能: 线性/非线性扩展状态观测器(ESO, Extended State Observer), 与状态误差
//       反馈组合成 ADRC(自抗扰控制)的核心运算: 观测被控量 z1、微分 z2、
//       总扰动 z3, 再按 u = [k*(c*z1+z2) + sign + c*z2 - z3] 生成控制量。
//
// 离散化形式(前向差分, 采样步长 h = 1/1024):
//   e(k)   = z1(k) - y(k)
//   z1(k+1) = z1(k) + h*z2(k) - B01*h*e(k)
//   z2(k+1) = z2(k) + h*z3(k) - B02*h*e(k) + b0*h*u(k)
//   z3(k+1) = z3(k)             - B03*h*e(k)
//
// 定点实现: 乘常数后用 >>>10 实现 *h, 用 >>>13/>>>15 做标度归一。
// 所有运算均为有符号补码, 位宽在每级手工扩展(见下方各 wire 声明)。
//==============================================================================
`timescale 1ns / 1ps 
//------------------------------------------------------------------------------
// `define WIDTH 20: 内部状态 z1/z2/z3 的位宽(20bit 有符号, 约 ±52 万)
//------------------------------------------------------------------------------
`define WIDTH 20 

module eso 
( 
//------------------------------------------------------------------------------
// 端口
//   ad_clk   : 观测器运算时钟(接 adda 的 ad_clk1 = 1kHz)
//   sys_rst_n: 异步复位, 低有效
//   e_in     : 测量误差输入(adda 送 date_y = AD 码值-512)
//   u_out    : 上一拍的控制量反馈(接 date_u), 用于 b0*u 项
//   c_flag/k_flag/c_date/k_date : 串口下发的两个可调参数 c、k
//   z1k0..z3k0 : 观测状态输出(本工程 adda 中未连接, 仅内部使用)
//   out_da     : 控制量输出(10bit), 接 adda 的 date_u -> DAC
//------------------------------------------------------------------------------
    input ad_clk, 
    input sys_rst_n, 
    input signed [9:0] e_in, 
    input signed [9:0] u_out, 
    input wire c_flag, 
    input wire k_flag, 
    input wire [11:0] c_date, 
    input wire [11:0] k_date, 
    
    output signed [`WIDTH-1: 0] z1k0, 
    output signed [`WIDTH-1: 0] z2k0, 
    output signed [`WIDTH-1: 0] z3k0, 
    output signed [9:0] out_da 
); 
    
//------------------------------------------------------------------------------
// 状态与寄存器
//   z1k1/z2k1/z3k1 : 上一拍(k)的观测状态, 位宽 `WIDTH
//   y   : 测量值(= -e_in), 即取反后的误差
//   uk  : 上一拍控制量
//   c   : 状态误差反馈系数(默认 150, 可由串口 A 帧修改)
//   k   : 反馈增益(默认 20, 可由串口 B 帧修改)
//------------------------------------------------------------------------------
reg signed [`WIDTH-1: 0] z1k1; 
reg signed [`WIDTH-1: 0] z2k1; 
reg signed [`WIDTH-1: 0] z3k1; 
reg signed [9:0] y; 
reg signed [9:0] uk; 
reg signed [9:0] c; 
reg signed [10:0] k; 

//------------------------------------------------------------------------------
// 系数(定点数): B01/B02/B03 为观测器增益, b0 为控制增益, n 未使用。
// 常数的实际比例由运算中的移位(>>>10 / >>>13)决定。
//------------------------------------------------------------------------------
parameter signed B01=21'd90; 
parameter signed B02=21'd2700; 
parameter signed B03=21'd27000; 
parameter signed b0=16'd5000; 
parameter signed n = 2'd1; 
 
//------------------------------------------------------------------------------
// (已废弃) 上电用 initial 直接赋 c/k 初值, 现改在复位分支中赋值。
//------------------------------------------------------------------------------
//initial 
//begin 
// c=10'd150; 
// k=11'd25; 
//end 
// 

//------------------------------------------------------------------------------
// [块 1] 状态打拍
//   zx_k1 <= zx_k0 : 把组合逻辑算出的 k+1 拍状态锁存为 k 拍状态(一级流水)
//   y  <= -e_in    : 误差取反(符号约定: 观测器用 -e)
//   uk <= u_out    : 控制量延迟一拍, 供 b0*u 项使用
// 复位时全部清零, 保证上电从 0 状态开始收敛。
//------------------------------------------------------------------------------
always@(posedge ad_clk or negedge sys_rst_n) 
    begin
        if(sys_rst_n==1'b0) 
            begin 
                z1k1 <= 'd0; 
                z2k1 <= 'd0; 
                z3k1 <= 'd0; 
                y <= 'd0; 
                uk <= 'd0; 
            end 
        else 
            begin 
                z1k1 <= z1k0; //z(k)=z(k+1) 
                z2k1 <= z2k0; 
                z3k1 <= z3k0; 
                y <= -e_in; 
                uk <= u_out; 
            end  
    end
    
//------------------------------------------------------------------------------
// [块 2] 参数锁存(c、k)
//   复位: c=150, k=20 (经验初值)
//   c_flag=1: c <= c_date
//   k_flag=1: k <= k_date
// 注意(设计隐患): 两条为 if/else-if 优先级结构, 且 adda.v 中的 c_flag/k_flag
//   置 1 后不清零 => 一旦收到过 A 帧, c_flag 恒为 1, k 将永远无法再被更新。
//   建议把两个 flag 改为单周期脉冲, 或改成两个独立的 if 分支。
//------------------------------------------------------------------------------
always@(posedge ad_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        begin 
            c<=10'd150; 
            k<=11'd20; 
        end //初始化参数 
    else if(c_flag==1'b1) 
        c<=c_date; 
    else if(k_flag==1'b1) 
        k<=k_date; 
    else 
        begin 
            c<=c; 
            k<=k; 
        end 
 
//------------------------------------------------------------------------------
// [语句组 1] u*b0 * h 项
//   uk_b0   = uk * 5000            (20+16=36bit)
//   uk_b0_h = uk_b0 >>> 13         (等价于 *5000/8192, 约 *0.61)
//------------------------------------------------------------------------------
wire signed [`WIDTH + 16 - 1 : 0] uk_b0; 
wire signed [`WIDTH + 16 - 1 : 0] uk_b0_h; 
assign uk_b0 = uk * b0; 
assign uk_b0_h = uk_b0 >>> 13; 

//------------------------------------------------------------------------------
// [语句组 2] z2*h、z3*h 项: 右移 10 位 = 乘 1/1024 = 乘采样步长 h
//------------------------------------------------------------------------------
wire signed [`WIDTH - 1: 0] z2k1_h; //z(k)*h 
wire signed [`WIDTH - 1: 0] z3k1_h; 
assign z2k1_h = z2k1 >>> 10; 
assign z3k1_h = z3k1 >>> 10; 

//------------------------------------------------------------------------------
// [语句组 3] 观测误差 e = z1 - y (宽度 WIDTH+1 = 21bit)
//------------------------------------------------------------------------------
wire signed [`WIDTH - 1 + 1: 0] sub; 
assign sub = z1k1 - y; 

//------------------------------------------------------------------------------
// [语句组 3'] e 分别乘三个观测器增益 B01=90 / B02=2700 / B03=27000
//------------------------------------------------------------------------------
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B01; 
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B02; 
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B03; 
assign sub_B01 = sub * B01; //B1e1,B2e1,B3e1 
assign sub_B02 = sub * B02; 
assign sub_B03 = sub * B03; 

//------------------------------------------------------------------------------
// [语句组 4] 再右移 10 位, 得到 B0x*h*e 项
//------------------------------------------------------------------------------
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B01_h; 
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B02_h; 
wire signed [`WIDTH - 1 + 1 + 21: 0] sub_B03_h; 
assign sub_B01_h = sub_B01 >>> 10; //Be1*h
assign sub_B02_h = sub_B02 >>> 10; 
assign sub_B03_h = sub_B03 >>> 10; 

//------------------------------------------------------------------------------
// [语句组 5] 三个观测方程的组合逻辑(对应文件头的差分方程组)
// 注意结果宽度为 44bit(声明 WIDTH+1+21+2), 高位为符号扩展位。
//------------------------------------------------------------------------------
wire signed [`WIDTH - 1 + 1 + 21 + 2: 0] z1k0_reg; 
wire signed [`WIDTH - 1 + 1 + 21 + 2: 0] z2k0_reg; 
wire signed [`WIDTH - 1 + 1 + 21 + 2: 0] z3k0_reg; 
assign z1k0_reg = z1k1 + z2k1_h - sub_B01_h; //前向差分 ESO 
assign z2k0_reg = z2k1 + z3k1_h - sub_B02_h + uk_b0_h; 
assign z3k0_reg = z3k1 - sub_B03_h; 

//------------------------------------------------------------------------------
// [语句组 6] 取低 22bit([21:0]) 驱动 z1k0/z2k0/z3k0, 并回灌到块 1 打拍。
// 直接取低 22 位属于'环绕'截断, 正常工作时高位为符号扩展, 不会溢出;
// 但若 z 状态发散, 这里会静默回绕(无饱和保护)。
//------------------------------------------------------------------------------
assign z1k0 = z1k0_reg[21: 0]; //z(k+1) 
assign z2k0 = z2k0_reg[21: 0]; 
assign z3k0 = z3k0_reg[21: 0]; 

//------------------------------------------------------------------------------
// [语句组 7] 状态误差反馈: s = c*z1 + z2 (err1=c*z1, err2=c*z2, she=err1+z2)
//   注意 she 只声明了 33bit, 而 err1(32bit)+z2k0(22bit) 最大需 34bit,
//   极端情况下最高位会被截掉, 属潜在的位宽不足点。
//------------------------------------------------------------------------------
wire signed [`WIDTH + 12 -1: 0] err1; 
wire signed [`WIDTH + 12 -1: 0] err2; 

assign err1 = z1k0 * c; 
assign err2 = z2k0 * c; 

wire signed [`WIDTH + 13 -1: 0] she ; 
assign she = err1 + z2k0; //s=ce1+e2 
//------------------------------------------------------------------------------
// [语句组 8] kshe = s * k (13+11 = 43bit 结果)
//------------------------------------------------------------------------------
wire signed [`WIDTH + 13 + 11 -1: 0] kshe; 
assign kshe = she * k; 

//------------------------------------------------------------------------------
// [语句组 9] 符号项 sgn: 设计意图是 s>0 取 +1, 否则取 -1。
// 注意(设计隐患): sgn 声明为 5bit 有符号, 但赋的 4'b1111 是无符号常量,
//   补零扩展后等于 +15, 而不是 -1。若要得到 -1 应写 -5'sd1。
//------------------------------------------------------------------------------
wire signed [4 : 0] sgn; 
assign sgn= (she>1'd0)?1'd1:4'b1111; 

//------------------------------------------------------------------------------
// [语句组 10] v_1 = k*s + sgn + c*z2  (线性状态误差反馈 + 符号补偿)
//------------------------------------------------------------------------------
wire signed [`WIDTH + 22 -1: 0] v_1; 
assign v_1 = kshe +sgn + err2; 

//------------------------------------------------------------------------------
// [语句组 11] viout = v_1 - z3 : 减去观测到的'总扰动', 实现扰动补偿
//------------------------------------------------------------------------------
wire signed [`WIDTH + 21 -1: 0] viout; 
assign viout = v_1 - z3k0; //ks+sgn+cz2-f 

//------------------------------------------------------------------------------
// [语句组 12] 输出标度: 右移 15 位压缩动态范围, 取低 10 位送 DAC(0~1023)。
//   右移 15 相当于除以 32768, 目的是把大位宽的控制量映射到 10bit DAC 量程。
//------------------------------------------------------------------------------
wire signed [40 -1: 0] b; 
assign b = viout >>> 15; 
assign out_da = b[9 : 0]; 
 
//------------------------------------------------------------------------------
// 附注: 本模块共有 9 个乘法器(1 个 e*B、3 个 e*B0x、1 个 u*b0、2 个 z*c、1 个 s*k),
// 综合后映射为 7 个 MULTALU27X18(见综合资源报告), 是设计中 DSP 的主要来源。
//------------------------------------------------------------------------------
endmodule 