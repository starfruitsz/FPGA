//==============================================================================
// 文件: divider.v        模块: divider        实例名: divider_inst(adda 顶层)
// 功能: 对 50MHz 系统时钟做偶数分频, 输出两路同相同频的方波, 作为外部 AD/DA
//       芯片的转换(采样)时钟。
// 计算: cnt_max=24999 -> 计数 25000 个周期翻转一次 -> 分频比 50000,
//       50MHz / 50000 = 1kHz(注意: 原注释'500 分频'与实参不符, 以 24999 为准)。
//==============================================================================
module divider
#(
//------------------------------------------------------------------------------
// 参数: 分频计数器上限(可被上层例化时覆盖, adda 中传入 24999)
//------------------------------------------------------------------------------
    parameter cnt_max=15'd24999   //500分频
)

(
    input wire sys_clk,
    input wire sys_rst_n,
    
    //output wire clk_flag
    output reg clk0,
    output reg clk1
    
);

//------------------------------------------------------------------------------
// 内部信号: 15bit 分频计数器, 0~cnt_max 循环
//------------------------------------------------------------------------------
reg [14:0] cnt;

//------------------------------------------------------------------------------
// [块 1] 分频计数器: 0..cnt_max 自由循环, 是两路输出的公共节拍。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n)
    if(sys_rst_n==1'b0)
        cnt<=15'd0;
    else if(cnt==cnt_max)
        cnt<=15'd0;
    else 
        cnt<=cnt+15'd1;

//------------------------------------------------------------------------------
// (已废弃) 原设计输出单周期 clk_flag 作为'分频完成'脉冲, 现改为直接翻转时钟, 保留注释。
//------------------------------------------------------------------------------
/*always@(posedge sys_clk or negedge sys_rst_n)
    if(sys_rst_n==1'b0)
        clk_flag<=1'b0;
    else if(cnt==cnt_max-1)
        clk_flag<=1'b1;
    else 
        clk_flag<=1'b0;*/

//------------------------------------------------------------------------------
// [块 2] 输出时钟 0: 每计满一次翻转, 占空比 50%,
// 频率 = 50MHz/(2*(24999+1)) = 1kHz。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n)
    if(sys_rst_n==1'b0)
        clk0<=1'b0;
    else if(cnt==cnt_max)
        clk0<=~clk0;
    else 
        clk0<=clk0;

//------------------------------------------------------------------------------
// [块 3] 输出时钟 1: 与 clk0 完全同步、同相, 供另一路(DA)使用。
// 说明: 用普通寄存器分频得到的时钟会走全局时钟网络, 建议在时序约束中为其
//       建立 create_generated_clock 或改用 PLL/时钟使能方式(见文档'改进建议')。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n)
    if(sys_rst_n==1'b0)
        clk1<=1'b0;
    else if(cnt==cnt_max)
        clk1<=~clk1;
    else 
        clk1<=clk1;

//------------------------------------------------------------------------------
// 附注: 该模块输出直接驱动 ad_clk1/da_clk1 引脚, 未做 ODDR 处理,
// 1kHz 的低速场合无影响; 若提高频率需考虑时钟输出相位与抖动。
//------------------------------------------------------------------------------
endmodule