//==============================================================================
// 文件: rtl.v            模块: rtl            实例名: adc_inst(位于 adda 顶层)
// 功能: AD 码值的中值(基准)提取与正/负向电压换算。
//   1) 上电后用 1024 个采样点求平均值, 作为 ADC 的'零点'(直流偏置);
//   2) 以该零点为界, 分别计算正向/负向每 LSB 对应的电压刻度(定点数);
//   3) 用当前码值与零点之差乘以刻度, 得到以 0.01V 为单位的电压值。
// 时钟: clk = sys_clk = 50MHz, 复位 rst_n 低有效。
// 注意: 中值只在复位后前 1024 个时钟一次性算出并锁存, 之后不再更新。
//==============================================================================
module rtl
( 
    input wire clk, 
    input wire rst_n, 
    input wire [9:0]ad_data, 
    
    output wire sign, 
    output wire [9:0]volt 
); 

//------------------------------------------------------------------------------
// 参数: 求中值的采样点数 = 1024(2^10, 除以它等价于右移 10 位, 无需除法器)
//------------------------------------------------------------------------------
parameter CNT_DATA_MAX=11'd1024; 

//------------------------------------------------------------------------------
// 内部寄存器
//   clk_sample : 预留(未使用)
//   median_en  : 中值就绪标志, 累加满 1024 点后置 1 且一直保持
//   cnt_median : 累加计数器, 0~1024
//   data_sum_m : 1024 点累加和(最大 1023*1024=1047552, 20bit 足够, 这里用 30bit)
//   data_median: 中值 = 累加和/1024, 即 ADC 直流零点
//   volt_reg   : 换算后的电压值(0.01V 单位)
//   data_p/data_n : 正向/负向每 LSB 的电压刻度, 定点表示
//------------------------------------------------------------------------------
reg clk_sample; 
reg median_en; 
reg [10:0]cnt_median; 
reg [29:0]data_sum_m; 
reg [13:0]data_median; 
reg [30:0]volt_reg; 

wire [30:0]data_p; 
wire [30:0]data_n; 

//------------------------------------------------------------------------------
// [语句 1] 符号判断: 当前码值低于零点 => sign=1(负数), 送数码管显示负号。
// (下一行 assign sign=1'b1 是调试用强制正号, 已注释)
//------------------------------------------------------------------------------
assign sign=(ad_data<data_median)? 1'b1:1'b0;  
//assign sign=1'b1; 

//------------------------------------------------------------------------------
// [块 1] 中值使能: cnt_median 计到 1024 时置 median_en=1 并保持。
// 由于 cnt_median 在 median_en=1 后停止计数(见下块), 该标志不会回落,
// 因此这是一次性的'上电自校准'。
//------------------------------------------------------------------------------
//中值使能信号 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        median_en<=1'b0; 
    else if(cnt_median==CNT_DATA_MAX) 
        median_en<=1'b1; 
    else 
        median_en<=median_en; 
 
//------------------------------------------------------------------------------
// [块 2] 累加计数器: median_en=0 期间每拍 +1, 计到 1024 保持。
// (没有 else 分支, 计满后 cnt_median 保持 1024, 与块 1 共同形成自锁)
//------------------------------------------------------------------------------
//中值数据累加计数器 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        cnt_median<=11'b0; 
    else if(!median_en) 
        cnt_median<=cnt_median+1'b1; 
 
//------------------------------------------------------------------------------
// [块 3] 1024 点累加: 未满 1024 时对 ad_data 累加, 满 1024 的那一拍清零,
// 为块 4 的除法提供'最后一拍的累加和'(注意清零与取商同拍, 由非阻塞赋值保证
// data_median 拿到的是清零前的和)。
//------------------------------------------------------------------------------
//1024 次中值数据累加总和 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        data_sum_m<=30'b0; 
    else if(cnt_median==CNT_DATA_MAX) 
        data_sum_m<=30'b0; 
    else 
        data_sum_m<=data_sum_m+ad_data; 
 
//------------------------------------------------------------------------------
// [块 4] 求中值: 累加和 / 1024, 综合工具会自动实现为 >>10。
// 结果 data_median 只在计满的那一拍更新一次, 之后保持不变(零点锁存)。
//------------------------------------------------------------------------------
//中值数据 
always @(posedge clk or negedge rst_n) 
    if(!rst_n)
        data_median<=12'b0; 
    else if(cnt_median==CNT_DATA_MAX) 
        data_median<=data_sum_m/CNT_DATA_MAX; 
    else 
        data_median<=data_median; 
 
//------------------------------------------------------------------------------
// [语句 2] 正/负向电压刻度(定点, 2^13*100 倍放大, 便于后续右移 13 位):
//   正向: data_p = 2^13*100*2/(1024-median)   (码值 >= 中值 时用)
//   负向: data_n = 2^13*100*2/(median+1)      (码值 <  中值 时用)
// 直观理解: 把 ±2V 满量程按各自的有效码值区间等分, 得到每 LSB 的电压。
// median_en=0 时输出 0, 避免除法在未标定时得到无意义值。
// 实现代价: 2 个 30bit 除法器, 综合后映射为多级流水/移位减法逻辑(占用一定 LUT)。
//------------------------------------------------------------------------------
//根据中值计算出的正向电压 AD 和负向电压 AD 的分辨率（放大 2^13*100 倍） 
assign data_p=(median_en==1'b1)?3276800/((1024-data_median)*2):0; 
assign data_n=(median_en==1'b1)?3276800/((data_median+1)*2):0; 
 
//------------------------------------------------------------------------------
// [块 5] 电压换算: volt = 刻度 * |ad_data - 中值| >> 13
//   1) 码值在中值 ±3 以内视为 0(去抖/死区, 防止零漂显示跳动);
//   2) 码值低于中值: 用负向刻度 data_n * (median-ad_data) 再 >>13;
//   3) 码值高于中值: 用正向刻度 data_p * (ad_data-median) 再 >>13;
// 结果单位: 0.01V(即真实电压 x100), 例: AD=1023、中值=512 -> 约 199 = 1.99V。
//------------------------------------------------------------------------------
//处理后的稳定数据 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        volt_reg<=1'b0; 
    else if(median_en) 
        if((ad_data>(data_median-3)) && (ad_data<(data_median+3))) 
            volt_reg<=1'b0; 
        else if(ad_data<data_median) 
            volt_reg<=(data_n*(data_median-ad_data)) >> 13; 
        else if(ad_data>data_median) 
            volt_reg<=(data_p*(ad_data-data_median)) >> 13; 
    else 
        volt_reg<=1'b0; 
 
//------------------------------------------------------------------------------
// [语句 3] 输出: volt_reg(31bit) 赋给 10bit 端口 volt 时被寄存器化并截断,
// 实际有效范围 0~1023(0~10.23V 显示量程)。
//------------------------------------------------------------------------------
assign volt=volt_reg; 
 
endmodule 