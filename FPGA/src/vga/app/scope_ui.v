//==============================================================================
// 层: 应用(人机)  文件: app/scope_ui.v
// 功能: 单按键的短按/长按识别(带去抖)
//   - 按下并稳定 DB_MS 毫秒后才认为有效
//   - 按住超过 LONG_MS 毫秒 -> ev_long 单周期脉冲(只发一次)
//   - 未达长按即松开 -> ev_short 单周期脉冲
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 机械按键按下/松开时会有几毫秒的抖动（触点反复通断），直接当信号用会“连按好几次”。
// 消抖的通用做法：只有在按键电平稳定一段时间（这里 20ms）后才承认它。
// 本模块还顺便区分“短按”和“长按”：
//   短按 = 按下后不到 800ms 就松开 → 发一个 ev_short 脉冲
//   长按 = 一直按住到 800ms     → 立刻发一个 ev_long 脉冲（松开时不再发短按）
// ======================================================================
module scope_ui #(
    parameter integer CLK_HZ  = 50_000_000,
    parameter integer DB_MS   = 20,
    parameter integer LONG_MS = 800
)(
    input  wire clk,
    input  wire rst,
    input  wire key_in,
    output reg  ev_short,
    output reg  ev_long
);

//------------------------------------------------------------------
// 把“毫秒”换算成“时钟个数”，这样换主频时只改 CLK_HZ 参数即可：
//   DB_CNT   = 50MHz/1000 * 20  = 1,000,000 个时钟 = 20ms
//   LONG_CNT = 50MHz/1000 * 800 = 40,000,000 个时钟 = 800ms
//------------------------------------------------------------------
    localparam integer DB_CNT   = (CLK_HZ / 1000) * DB_MS;
    localparam integer LONG_CNT = (CLK_HZ / 1000) * LONG_MS;

//------------------------------------------------------------------
// key_sync：3 位移位寄存器，把异步的按键信号“同步”到本时钟域。
// 直接用外部信号会有亚稳态风险（触发器可能采到 0 和 1 之间的电平），
// 打两拍以上就能把风险降到可接受范围，这是 FPGA 的基本功。
// pressed/long_fired：当前是否已确认按下 / 长按是否已经触发过。
//------------------------------------------------------------------
    reg [2:0]  key_sync;
    reg [23:0] db_cnt;
    reg [27:0] hold_cnt;
    reg        pressed;
    reg        long_fired;

    always @(posedge clk) begin
        if (rst) begin
            key_sync   <= 3'b111;
            db_cnt     <= 24'd0;
            hold_cnt   <= 28'd0;
            pressed    <= 1'b0;
            long_fired <= 1'b0;
            ev_short   <= 1'b0;
            ev_long    <= 1'b0;
        end
        else begin
//------------------------------------------------------------------
// 每拍把新采样移入最低位，最高位 key_sync[2] 就是“打过两拍后的按键电平”。
// 下面所有判断都用 key_sync[2]，不再直接看 key_in。
//------------------------------------------------------------------
            key_sync <= {key_sync[1:0], key_in};
            ev_short <= 1'b0;
            ev_long  <= 1'b0;

//------------------------------------------------------------------
// [松开分支]：如果之前确认过按下，且没有触发长按，就发一个短按脉冲。
// 然后把所有计数器清零，等待下一次按下。
// 脉冲之所以只持续 1 拍，是因为每拍开头都先把 ev_short/ev_long 清 0。
//------------------------------------------------------------------
            if (key_sync[2] == 1'b1) begin          // 松开
                if (pressed && !long_fired)
                    ev_short <= 1'b1;
                pressed    <= 1'b0;
                long_fired <= 1'b0;
                db_cnt     <= 24'd0;
                hold_cnt   <= 28'd0;
            end
            else begin                              // 按下
//------------------------------------------------------------------
// [按下消抖]：数够 DB_CNT(20ms) 才把 pressed 置 1；中途松开会被清零重来。
// 这就是消抖的本质——短于 20ms 的抖动永远数不满。
//------------------------------------------------------------------
                if (!pressed) begin
                    if (db_cnt == DB_CNT)
                        pressed <= 1'b1;
                    else
                        db_cnt <= db_cnt + 24'd1;
                end
//------------------------------------------------------------------
// [长按检测]：按下确认后开始数 hold_cnt，数到 LONG_CNT(800ms)
// 立刻发 ev_long，并用 long_fired 记住“已经发过”，避免松开时再发短按。
//------------------------------------------------------------------
                else if (!long_fired) begin
                    if (hold_cnt == LONG_CNT) begin
                        ev_long    <= 1'b1;
                        long_fired <= 1'b1;
                    end
                    else begin
                        hold_cnt <= hold_cnt + 28'd1;
                    end
                end
            end
        end
    end

endmodule
