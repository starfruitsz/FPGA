//==============================================================================
// 层: 应用(采集)  文件: app/scope_capture.v
// 功能: 单通道采样引擎
//   - 采样率 = CLK / (rate_div+1)，rate_div 运行时可配(0 => 每个时钟采一点)
//   - 循环写入 BSRAM，写指针 arm 时归零
//   - 【特性1 触发】trig_en=1 时，检测到电平穿越就把写指针归零，
//     显示总是从触发点开始(±1 采样)，周期信号不再左右漂移
//   - run=0 冻结(停止写入，保留当前波形)
// 说明: 采样数据由顶层直连 RAM 的 wdata，与写地址同拍，第 0 个样本落在地址 0。
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 采集引擎负责“多久采一个点、存到哪里、什么时候重来”。
// 它内部其实只有两样东西：一个分频计数器(rate_cnt) 和 一个写地址(waddr)。
// 写进 RAM 的数据由顶层直接连过去（din → RAM.wdata），本模块只给“写使能+地址”。
// 【触发】的作用：示波器上周期信号会左右漂，是因为每次采集的起点不同。
// 这里用“检测到电平穿越时把写地址清零”来对齐，相当于给波形找了个固定起点。
// ======================================================================
module scope_capture #(
    parameter integer DEPTH_LOG2 = 10
)(
    input  wire                    clk,
    input  wire                    rst,
    input  wire [9:0]              din,        // 采样数据(仅用于触发检测)
    input  wire [15:0]             rate_div,
    input  wire                    run,
    input  wire                    arm,
    input  wire                    trig_en,
    input  wire [9:0]              trig_level,
    input  wire                    trig_edge,    // 0=上升沿 1=下降沿
    output wire                    we,
    output reg  [DEPTH_LOG2-1:0]   waddr,
    output reg                     trig_det     // 触发命中(单周期)
);

//------------------------------------------------------------------
// rate_cnt：采样间隔计数器，从 0 数到 rate_div；
// din_d：上一拍的采样值，用来判断“有没有跨过触发电平”。
//------------------------------------------------------------------
    reg [15:0] rate_cnt;
    reg [9:0]  din_d;

//------------------------------------------------------------------
// tick：本拍该不该采一个点。
// 采样周期 = (rate_div+1) 个时钟；rate_div=0 时每个时钟都采（50MS/s）。
// 例如 rate_div=49999 → 50MHz/50000 = 1kS/s，正好每 1ms 采一个点。
//------------------------------------------------------------------
    wire tick = (rate_cnt == rate_div);

//------------------------------------------------------------------
// 写使能是“组合逻辑”：它和 waddr、wdata 必须在同一拍有效，
// 这样第 0 个样本才会写到地址 0（如果改成寄存器输出，会整体错一位）。
// 条件：正在运行、不是刚按了复位采集、且到达采样时刻。
//------------------------------------------------------------------
    assign we = run && (!arm) && tick;

    // 上升沿: 上一拍 < 阈值 且 本拍 >= 阈值；下降沿: 上一拍 > 阈值 且 本拍 <= 阈值
//------------------------------------------------------------------
// [触发判据] 比较“上一拍采样”和“本拍采样”与触发电平的关系：
//   上升沿：上一拍 < 电平，且本拍 >= 电平
//   下降沿：上一拍 > 电平，且本拍 <= 电平
// 这样即使信号抖动几次，也只会在地平线附近正常触发，不会误触发到别处。
//------------------------------------------------------------------
    wire cross = trig_edge
               ? ((din_d > trig_level) && (din <= trig_level))
               : ((din_d < trig_level) && (din >= trig_level));

//------------------------------------------------------------------
// 主状态机（用 if/else 优先级实现，没有单独的状态寄存器）：
//   复位 > arm(重新开始) > 冻结 > 到达采样时刻 > 继续计数
// 每一拍的优先级从高到低判断，逻辑清晰，也便于综合。
//------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            rate_cnt <= 16'd0;
            waddr    <= {DEPTH_LOG2{1'b0}};
            din_d    <= 10'd0;
            trig_det <= 1'b0;
        end
        else begin
            trig_det <= 1'b0;

//------------------------------------------------------------------
// arm：来自按键/串口的一次性脉冲，表示“从头开始采一屏”。
// 把写地址清零，后面的数据就会从地址 0 依次写入。
//------------------------------------------------------------------
            if (arm) begin
                rate_cnt <= 16'd0;
                waddr    <= {DEPTH_LOG2{1'b0}};
                din_d    <= din;
            end
            else if (!run) begin
                rate_cnt <= 16'd0;
            end
//------------------------------------------------------------------
// 到达采样时刻：更新“上一拍采样”，然后把写地址 +1。
// 如果触发有效且检测到穿越，则把地址清零——这就是“触发对齐”。
// 注意：清零后下一个点写到 0，触发点本身落在“上一个地址”，
// 所以显示上会差 1 个采样，对波形观测没有影响。
//------------------------------------------------------------------
            else if (tick) begin
                rate_cnt <= 16'd0;
                din_d    <= din;
                if (trig_en && cross) begin
                    trig_det <= 1'b1;
                    waddr    <= {DEPTH_LOG2{1'b0}};   // 触发对齐
                end
                else begin
                    waddr    <= waddr + 1'b1;
                end
            end
            else begin
                rate_cnt <= rate_cnt + 16'd1;
            end
        end
    end

endmodule
