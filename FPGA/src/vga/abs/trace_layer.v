//==============================================================================
// 层: 抽象(图形层)  文件: abs/trace_layer.v
// 功能: 单通道波形图层(流式渲染，无帧缓存)
//   对当前像素列 px 取两个相邻采样 s_now/s_prev，分别映射成绘图区 y 坐标，
//   若当前扫描线 py 落在两者之间，则该像素点亮 => 自动连成波形。
// 映射: y = (PLOT_H-1) - (s * SCALE_NUM >> SCALE_SHIFT)
//       默认 10bit(0..1023) -> 0..447，取 7/16 缩放
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 这是“画波形”的核心技巧，初学者最值得先看懂的一段。
// 我们没有帧缓存，没法“先画点再连线”，所以换一个思路：
//   对当前像素列 x，读出这一列的采样值和上一列的采样值，
//   如果当前扫描线 y 正好落在这两个值之间，就点亮这个像素。
// 效果上等价于“把相邻两个采样点用一根竖线连起来”，画出来就是连续波形。
// ======================================================================
module trace_layer #(
    parameter integer H_VIS       = 640,
    parameter integer PLOT_H      = 448,
    parameter integer SCALE_NUM   = 7,
    parameter integer SCALE_SHIFT = 4,
    parameter [11:0]  COL         = 12'h1F1
)(
    input  wire [11:0] px,
    input  wire [11:0] py,
    input  wire        de,
    input  wire        en,        // 通道使能
    input  wire [9:0]  s_now,     // 当前列采样
    input  wire [9:0]  s_prev,    // 前一列采样
    input  wire [2:0]  vshift,    // 垂直档位: 右移位数(2..7)，越大波形越高
    input  wire signed [12:0] voff,// 垂直位置偏移：(pos-5)*24 + 精细居中(±1900)
    output wire        hit,
    output wire [11:0] color
);

//------------------------------------------------------------------
// 先把 10bit 采样值乘以 SCALE_NUM(7)，相当于放大 7 倍，
// 后面再右移 4 位（除以 16），整体得到 7/16 的缩放比例：
//   1023 * 7 / 16 ≈ 447，正好铺满 0..447 的绘图区。
// 为什么不用除法器？乘法+移位在 FPGA 里是纯 LUT，不需要 DSP，也不会引入时钟。
//------------------------------------------------------------------
    localparam [11:0] PLOT_TOP = PLOT_H - 1;
    // 有符号版的上边界：raw 坐标是 13bit 有符号，和它比较必须用有符号常量，
    // 否则负数会被当成大正数（Verilog 里 signed 与 unsigned 混算会整体转无符号）
    localparam signed [18:0] Y_MAX = PLOT_H - 1;

    // 运行时缩放：以 512 为中心放大 7 倍后右移 vshift 位
    //   vshift=4 -> 增益 7/16 = 0.4375（满量程铺满 448 像素，与旧版一致）
    //   vshift=3 -> 0.875（放大 2 倍）  vshift=7 -> 0.055（缩小 8 倍）
    // 位宽说明：d 是 ±511，乘 7 后最大 3577，右移前要留够位宽；
    // 再加上精细居中(±1900)，统一用 19bit 有符号运算，最后再限幅
    // 行首防假线：像素流水线有 1 拍延迟，屏幕最左边一两列取到的"上一个采样"
    // 其实来自消隐期（地址是上一行末尾附近的），两点相差很远，连起来就是
    // 屏幕左边缘的一条竖线。行首几列直接令 prev = now，只画一个点，不连线。
    wire [9:0] s_prev_eff = (px <= 12'd4) ? s_now : s_prev;

    wire signed [14:0] d_now  = $signed({5'b00000, s_now})       - 15'sd512;
    wire signed [14:0] d_prev = $signed({5'b00000, s_prev_eff})  - 15'sd512;
    wire signed [18:0] z_now  = (d_now  * 13'sd7) >>> vshift;
    wire signed [18:0] z_prev = (d_prev * 13'sd7) >>> vshift;
    wire signed [18:0] o      = $signed({{6{voff[12]}}, voff});

//------------------------------------------------------------------
// [坐标翻转] 屏幕 y 向下增大，而电压越高波形应该越靠上，
// 所以用 (PLOT_TOP - 缩放值) 做镜像：采样值 1023 → y=0（最上面），
// 采样值 0 → y=447（最下面）。
//------------------------------------------------------------------
    // 中心 224 + 垂直偏移，最后限幅到绘图区
    wire signed [18:0] yn_raw = 19'sd223 - z_now  + o;
    wire signed [18:0] yp_raw = 19'sd223 - z_prev + o;
    wire [11:0] y_now  = (yn_raw < 0)      ? 12'd0 :
                         (yn_raw > Y_MAX)  ? PLOT_TOP[11:0] : yn_raw[11:0];
    wire [11:0] y_prev = (yp_raw < 0)      ? 12'd0 :
                         (yp_raw > Y_MAX)  ? PLOT_TOP[11:0] : yp_raw[11:0];

//------------------------------------------------------------------
// [边缘假线修正] 限幅只是把越界点压回 0 / PLOT_TOP，坐标本身不可见。
// 如果相邻两个采样点都在屏幕同一侧之外，整段连线其实一点都看不到，
// 但限幅后它们变成 (0,0) 或 (447,447)，于是屏幕上边缘/下边缘会多出
// 一条本不存在的直线 —— 这就是"边缘假线"。
// 判据：两端同在上方 或 同在下方才整段不画；
//       一端在外、另一端在里（跨越边界）时照常画，限幅后的那一段正好
//       就是可见部分，不会多画也不会少画。
//
// [补充修正 2026-10] "值正好落在 0/447 边界且整段都在屏外"：
//   上面的判据只认"严格在屏外"(<0 / >447)。如果端点算出 y 恰好等于 0
//   （或恰好 447），它不算越界，于是被当成可见点在边界行上点亮；一列一个点
//   连起来就是贴着屏幕上/下边缘的一条直线（基线被推到屏外时最容易看到）。
//   现在把这种情况也归入"整段不可见"：
//     两端都 <= 0（或都 >= 447）且至少有一端真的越界 -> 不画
//   注意不能一刀切成 "<="：两端都严格等于 0（或 447）时，这一段本身就是
//   真实数据落在边界行上（例如满量程方波的两条水平沿），必须保留。
//------------------------------------------------------------------
    wire seg_off_top = (yn_raw <= 0)     && (yp_raw <= 0)     &&
                       ((yn_raw < 0)     || (yp_raw < 0));
    wire seg_off_bot = (yn_raw >= Y_MAX) && (yp_raw >= Y_MAX) &&
                       ((yn_raw > Y_MAX) || (yp_raw > Y_MAX));

//------------------------------------------------------------------
// 把“本列 y”和“上一列 y”排序，得到区间 [y_lo, y_hi]；
// 当前 py 落在这个区间内就点亮 —— 这就是那根连接线。
//------------------------------------------------------------------
    wire [11:0] y_hi = (y_now > y_prev) ? y_now : y_prev;
    wire [11:0] y_lo = (y_now > y_prev) ? y_prev : y_now;

    // px != 0: 避免行首与上一行末列"连"出一条竖线
//------------------------------------------------------------------
// [为什么有 px != 0] 第 0 列的“上一列”其实是上一行最后一列的数据，
// 如果不过滤，屏幕左边缘会出现一条莫名其妙的竖线（初学者常见 bug）。
// 其余条件：通道使能、在可见区、在绘图区内。
//------------------------------------------------------------------
    assign hit = en && de && (px != 12'd0) && (px < H_VIS) && (py < PLOT_H)
                 && (!seg_off_top) && (!seg_off_bot)
                 && (py >= y_lo) && (py <= y_hi);
    assign color = COL;

endmodule
