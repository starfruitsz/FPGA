//==============================================================================
// 层: 抽象(合成器)  文件: abs/compositor.v
// 功能: 按优先级把多个图层合成为一个像素(RGB444)
//   优先级: 文字 > CH1 波形 > CH0 波形 > 网格 > 背景
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 合成器就是“图层的叠加顺序”。每个图层都会说“我命中了吗(hit)”，
// 这里按优先级从高到低依次判断，第一个命中的决定最终颜色。
// 优先级：文字 > CH1 波形 > CH0 波形 > 网格 > 背景。
// 为什么文字最高？因为参数读数不能被波形盖住。
// ======================================================================
module compositor (
    input  wire        txt_hit,
    input  wire [11:0] txt_col,
    input  wire        ch1_hit,
    input  wire [11:0] ch1_col,
    input  wire        ch0_hit,
    input  wire [11:0] ch0_col,
    input  wire        grid_hit,
    input  wire [11:0] grid_col,
    input  wire [11:0] bg_col,
    output reg  [11:0] rgb
);

//------------------------------------------------------------------
// always @(*) 表示组合逻辑：输入一变，输出立刻变（没有时钟、没有存储）。
// 这里用 if/else if 链实现“优先级选择”，综合后会变成一棵多路选择器(MUX)树。
//------------------------------------------------------------------
    always @(*) begin
//------------------------------------------------------------------
// 从高到低逐个判断；都不命中时输出背景色 bg_col。
// 初学者提示：if 链的顺序就是优先级，写反了会导致“波形盖住文字”。
//------------------------------------------------------------------
        if (txt_hit)
            rgb = txt_col;
        else if (ch1_hit)
            rgb = ch1_col;
        else if (ch0_hit)
            rgb = ch0_col;
        else if (grid_hit)
            rgb = grid_col;
        else
            rgb = bg_col;
    end

endmodule
