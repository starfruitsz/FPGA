//==============================================================================
// 层: 抽象(图形层)  文件: abs/grid_layer.v
// 功能: 网格/坐标轴图层。只对当前像素(px,py)给出"是否命中"和颜色，
//       本身不存任何像素，因此不占显存。
// 说明: STEP 建议取 2 的幂(64/32/16)，内部的取模被优化成位与。
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 这一层叫“图层”：它不保存整屏图像，只回答一个问题——
//   “当前正在扫描的这个像素 (px,py)，我要不要画？画什么颜色？”
// 这种写法叫“流式渲染/即时判定”，好处是零显存、零 RAM 访问，
// 代价是每个像素都要做一次组合判断（几十个 LUT，很便宜）。
// 网格的作用是给示波器提供刻度参考：每 64 像素一根线，中间一行是零电平轴。
// ======================================================================
module grid_layer #(
    parameter integer H_VIS    = 640,
    parameter integer PLOT_H   = 448,
    parameter integer STEP     = 64,
    parameter integer AXIS_Y   = 224,
    parameter [11:0]  COL_GRID = 12'h151,
    parameter [11:0]  COL_AXIS = 12'h2A2
)(
    input  wire [11:0] px,
    input  wire [11:0] py,
    input  wire        de,
    output wire        hit,
    output wire [11:0] color
);

//------------------------------------------------------------------
// [小技巧] STEP=64 时，MASK=63(0b111111)。判断“是不是 64 的整数倍”
// 只需要 (px & 63)==0，比取模运算(px % 64)省得多——综合器对位与是零成本的。
// 所以这个参数约定必须取 2 的幂（16/32/64/128）。
//------------------------------------------------------------------
    localparam integer MASK = STEP - 1;

//------------------------------------------------------------------
// in_plot：只有“在可见区 + 在绘图区高度内”才允许画网格。
// 底部两行留给文字（py>=PLOT_H），网格不能盖上去。
//------------------------------------------------------------------
    wire in_plot = de && (px < H_VIS) && (py < PLOT_H);
//------------------------------------------------------------------
// v_line/h_line：竖线/横线的判定，本质就是“坐标低 6 位是否为 0”。
// axis：零电平轴（采样值 512 对应的那一行），单独用更亮的颜色。
//------------------------------------------------------------------
    wire v_line  = ((px & MASK) == 0);      // 竖网格
    wire h_line  = ((py & MASK) == 0);      // 横网格
    wire axis    = (py == AXIS_Y);          // 零电平轴

//------------------------------------------------------------------
// [输出约定] hit=1 表示“这个像素由本图层负责”，color 是它的颜色。
// 合成器会根据 hit 和优先级决定最终颜色；本图层优先级最低。
//------------------------------------------------------------------
    assign hit   = in_plot && (v_line || h_line || axis);
    assign color = axis ? COL_AXIS : COL_GRID;

endmodule
