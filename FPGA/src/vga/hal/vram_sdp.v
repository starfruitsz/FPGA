//==============================================================================
// 层: HAL(底层)  文件: hal/vram_sdp.v
// 功能: 简单双端口 RAM 封装(1 写 1 读, 同步读)
//   按 Gowin/Anlogic/Xilinx 通用写法编码，综合器会自动推断为 BSRAM/BRAM。
//   写优先: 同一时钟域、不同地址，读写互不干扰。
// 参数: DW 数据位宽, AW 地址位宽(深度=2^AW)
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 这是一个“一个写口 + 一个读口”的 RAM（叫简单双口 RAM，SDP）。
// 在本工程里，它用来存 AD 采样点：采集逻辑往里写，显示逻辑往外读。
// 为什么不用 reg 数组硬写？因为在 FPGA 里，只有写成“同步读”的固定套路，
// 综合工具才会把它识别成片内 BSRAM（块 RAM）；写成组合读会变成几万个 LUT，
// 资源瞬间爆掉。下面的写法就是最标准的 BSRAM 推断模板。
// ======================================================================
module vram_sdp #(
    parameter integer DW = 10,
    parameter integer AW = 10
)(
    input  wire          clk,
    input  wire          we,
    input  wire [AW-1:0] waddr,
    input  wire [DW-1:0] wdata,
    input  wire [AW-1:0] raddr,
    output reg  [DW-1:0] rdata
);

//------------------------------------------------------------------
// 存储器本体：2^AW 个单元，每个 DW 位。
//   本工程 AW=10、DW=10 → 1024 个点，每个点 10bit（正好是一个 AD 码值）。
// 注意：这里没有复位。RAM 一般不做复位（复位整个 1024x10 的阵列代价太大），
// 上电后内容是随机的，所以显示前要先写一遍数据（采集引擎会做）。
//------------------------------------------------------------------
    reg [DW-1:0] mem [0:(1<<AW)-1];

    always @(posedge clk) begin
//------------------------------------------------------------------
// [写口] 只有 we=1 的那一拍才写入；地址 waddr、数据 wdata 与 we 同拍有效。
// 非阻塞赋值 <= 表示“时钟沿到来时一起更新”，这是写 RAM 的标准写法。
//------------------------------------------------------------------
        if (we)
            mem[waddr] <= wdata;
    end

    always @(posedge clk) begin
//------------------------------------------------------------------
// [读口] 同步读：地址 raddr 给出后，要等到下一个时钟沿，rdata 才变成对应数据。
// 这就是“1 拍读延迟”。上层（trace_layer）必须知道这一点：
// 地址和像素坐标要错开一拍用，否则波形会整体左移一个像素。
// 初学者提示：看到 BSRAM 就读不到“当拍数据”，这不是 bug，是硬件的物理特性。
//------------------------------------------------------------------
        rdata <= mem[raddr];
    end

endmodule
