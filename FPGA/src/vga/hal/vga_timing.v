//==============================================================================
// 层: HAL(底层硬件抽象)  文件: hal/vga_timing.v
// 功能: 通用 VGA 时序发生器（与厂商无关，纯 RTL）
//   - 参数化：分辨率/前后肩/同步宽度/同步极性/像素使能分频
//   - 输出 px/py 为"当前像素坐标"，pix_ce 为像素节拍
//   - 不产生时钟：用 pix_ce 在系统时钟域内节拍化，避免派生时钟
// 使用: 640x480@60 取 H_VIS=640,H_FP=16,H_SYNC=96,H_BP=48,
//        V_VIS=480,V_FP=10,V_SYNC=2,V_BP=33, H_POL=0,V_POL=0, PIX_DIV=2
//       (50MHz/2 = 25MHz 像素节拍，59.5Hz)
//==============================================================================
`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 这个模块只做一件事：告诉上层“现在扫描到屏幕的哪个像素了”，并产生 HS/VS 同步。
// 你可以把它想象成老式 CRT 的电子枪：从左到右扫 800 个点（其中 640 个可见），
// 扫完一行就跳到下一行，扫完 525 行（其中 480 行可见）回到左上角，周而复始。
// 本模块不产生任何新时钟，只在 clk 的节拍下数数，因此最稳妥、最容易移植。
//
// 参数怎么填（640x480@60 的例子）：
//   H_VIS=640  一行里真正显示的点数
//   H_FP=16    行同步前肩（显示完到同步开始之间的空档）
//   H_SYNC=96  行同步脉冲宽度（显示器靠它识别“新的一行开始了”）
//   H_BP=48    行同步后肩（同步结束到下一行显示开始之间的空档）
//   V_* 同理，只是换成“行数”而不是“像素数”
//   H_POL/V_POL 同步极性：640x480 是负极性(0)，800x600 是正极性(1)
//   PIX_DIV    几个系统时钟出一个像素：50MHz / 2 = 25MHz
// ======================================================================
module vga_timing #(
    parameter integer H_VIS   = 640,
    parameter integer H_FP    = 16,
    parameter integer H_SYNC  = 96,
    parameter integer H_BP    = 48,
    parameter integer V_VIS   = 480,
    parameter integer V_FP    = 10,
    parameter integer V_SYNC  = 2,
    parameter integer V_BP    = 33,
    parameter integer H_POL   = 0,     // 0=同步负极性(640x480) 1=正极性(800x600)
    parameter integer V_POL   = 0,
    parameter integer PIX_DIV = 2      // 像素节拍分频: 2 => 50MHz/2 = 25MHz
)(
    input  wire        clk,
    input  wire        rst,
    output wire        pix_ce,   // 像素节拍(高有效)
    output wire        hs,
    output wire        vs,
    output wire        de,       // 有效显示区
    output wire [11:0] px,       // 0 .. H_VIS-1
    output wire [11:0] py        // 0 .. V_VIS-1
);

//------------------------------------------------------------------
// 一行/一场的总长度（含消隐区）。显示器只“看见”可见区，但同步必须按总长走。
//   一行 = 640 可见 + 16 前肩 + 96 同步 + 48 后肩 = 800 个像素周期
//   一场 = 480 可见 + 10 前肩 + 2  同步 + 33 后肩 = 525 行
// 这也是为什么 25MHz 像素时钟下，行频 = 25MHz/800 = 31.25kHz、
// 场频 = 31.25kHz/525 = 59.5Hz，正好落在显示器可接受的范围内。
//------------------------------------------------------------------
localparam integer H_TOTAL = H_VIS + H_FP + H_SYNC + H_BP;   // 800
localparam integer V_TOTAL = V_VIS + V_FP + V_SYNC + V_BP;   // 525

//------------------------------------------------------------------
// 三个计数器（寄存器）：
//   hcnt    当前是一行中的第几个像素（0 ~ 799）
//   vcnt    当前是第几行（0 ~ 524）
//   div_cnt 当前像素周期内走到第几个系统时钟（0 ~ PIX_DIV-1）
// 用 reg 而不是 wire，是因为它们要在时钟上升沿更新（时序逻辑）。
//------------------------------------------------------------------
reg [11:0] hcnt;
reg [11:0] vcnt;
reg [7:0]  div_cnt;

//------------------------------------------------------------------
// 像素节拍: 每 PIX_DIV 个系统时钟产生 1 个像素
// 用"计数器最高值"作为节拍标志，使像素数据在本拍后半段稳定
//------------------------------------------------------------------
always @(posedge clk) begin
    if (rst)
        div_cnt <= 8'd0;
    else if (div_cnt == PIX_DIV-1)
        div_cnt <= 8'd0;
    else
        div_cnt <= div_cnt + 8'd1;
end

//------------------------------------------------------------------
// [关键概念] 为什么用 pix_ce（时钟使能）而不是直接分频出一个 25MHz 时钟？
//   初学者常见做法是 always @(posedge clk) clk25 <= ~clk25; 然后用 clk25 当时钟。
//   这样做会多出一个时钟域：跨时钟域的信号要同步，时序分析也变复杂。
//   本设计改成“所有逻辑都在 50MHz 下跑，但每 2 拍才允许前进一个像素”，
//   这个“允许”就是 pix_ce。它只在 div_cnt 数到 PIX_DIV-1 时为 1，
//   也就是像素周期的最后一拍——此时图像数据已经稳定，正好用来采样/输出。
//------------------------------------------------------------------
assign pix_ce = (div_cnt == PIX_DIV-1);

//------------------------------------------------------------------
// 行列计数: 仅在像素节拍推进一次，保证 px/py 在整个像素周期内稳定
//------------------------------------------------------------------
//------------------------------------------------------------------
// [块 2] 行列计数：只在 pix_ce=1 的那一拍前进一格
//   这样 px/py 会在整个像素周期（2 个系统时钟）内保持不变，
//   后面的图层计算和 BSRAM 读取才有稳定的坐标可用。
//   注意：rst 是同步复位（只在时钟沿生效），工程里由顶层把异步复位同步化后送来。
//------------------------------------------------------------------
always @(posedge clk) begin
    if (rst) begin
        hcnt <= 12'd0;
        vcnt <= 12'd0;
    end
    else if (pix_ce) begin
//------------------------------------------------------------------
// 行尾回卷：数到一行的最后一个像素（799）就回到 0，同时行号 +1；
// 行号数到最后一行（524）时也归零，形成“一场”的循环。
// 这里用嵌套 if，是因为“换行”和“换场”必须同时发生。
//------------------------------------------------------------------
        if (hcnt == H_TOTAL-1) begin
            hcnt <= 12'd0;
            if (vcnt == V_TOTAL-1)
                vcnt <= 12'd0;
            else
                vcnt <= vcnt + 12'd1;
        end
        else begin
            hcnt <= hcnt + 12'd1;
        end
    end
end

assign px = hcnt;
assign py = vcnt;

//------------------------------------------------------------------
// 同步信号/有效区
//   hs_act = 处于行同步窗口内(逻辑有效)；H_POL 决定最终电平
//------------------------------------------------------------------
//------------------------------------------------------------------
// [块 3] 同步信号与有效区
//   hs_act=1 表示“当前处于行同步脉冲期间”（这是逻辑意义上的有效），
//   最终输出电平由极性 H_POL 决定：负极性时把 hs_act 取反。
//   显示器就是靠这个脉冲的边沿来对齐每一行，所以它必须严格按上面的
//   前肩/同步/后肩顺序出现，否则画面会左右偏移或抖动。
//------------------------------------------------------------------
wire hs_act = (hcnt >= (H_VIS+H_FP)) && (hcnt < (H_VIS+H_FP+H_SYNC));
wire vs_act = (vcnt >= (V_VIS+V_FP)) && (vcnt < (V_VIS+V_FP+V_SYNC));

assign hs = H_POL ? hs_act : ~hs_act;
assign vs = V_POL ? vs_act : ~vs_act;
//------------------------------------------------------------------
// de（Data Enable）=“当前像素位于可见区内”。
// 只有 de=1 时，上层图层才需要计算颜色；de=0 的消隐期输出背景色即可，
// 这样能省掉大量无意义的比较运算。
// 三个输出连线总结：
//   hs  每 800 个像素周期出现一次同步脉冲
//   vs  每 525 行出现一次同步脉冲
//   de  只有前 640 列、前 480 行同时满足时为 1
//------------------------------------------------------------------
assign de = (hcnt < H_VIS) && (vcnt < V_VIS);

endmodule
