`timescale 1ns / 1ps

//
// ============================ 怎么读这个文件 ============================
// 这是“字符点阵表”：告诉显示器每一个字符长什么样。
// 编码方式：一个字符占 8x8 个像素，共 8 行，每行 8 个点，一个点用 1bit 表示亮/灭。
// 8 行 x 8bit = 64bit，所以每个字符用一个 64 位常量表示（行 0 放在最高 8 位）。
// 本文件只收录了工程用到的 38 个字符（0-9、A-F、常用字母与符号），
// 查表用的是组合逻辑 case，会被综合成 LUT（只读），不占 BSRAM。
// 想加新字符：在 case 里加一条 64'h....，并在注释里写明是什么字符即可。
// ======================================================================
               module font_rom (
    input  wire [5:0] ch,
    input  wire [2:0] row,
    output wire [7:0] bits
);

//------------------------------------------------------------------
// glyph：当前字符的 64 位点阵。always @(*) 表示“输入一变就重新计算”，
// 属于组合逻辑（没有时钟），所以查表结果是当拍就能用的。
//------------------------------------------------------------------
    reg [63:0] glyph;   // 8 行 x 8 bit，行 0 在最高字节

    always @(*) begin
        case (ch)
            6'd0 : glyph = 64'h7C44444444447C00;   // '0'
            6'd1 : glyph = 64'h0C04040404040400;   // '1'
            6'd2 : glyph = 64'h7C04047C40407C00;   // '2'
            6'd3 : glyph = 64'h7C04047C04047C00;   // '3'
            6'd4 : glyph = 64'h4444447C04040400;   // '4'
            6'd5 : glyph = 64'h7C40407C04047C00;   // '5'
            6'd6 : glyph = 64'h7C40407C44447C00;   // '6'
            6'd7 : glyph = 64'h7C04040404040400;   // '7'
            6'd8 : glyph = 64'h7C44447C44447C00;   // '8'
            6'd9 : glyph = 64'h7C44447C04047C00;   // '9'
            6'd10: glyph = 64'h3844447C44444400;   // 'A'
            6'd11: glyph = 64'h7844447844447800;   // 'B'
            6'd12: glyph = 64'h3844404040443800;   // 'C'
            6'd13: glyph = 64'h7844444444447800;   // 'D'
            6'd14: glyph = 64'h7C40407840407C00;   // 'E'
