            6'd18: glyph = 64'h7C10101010107C00;   // 'I'
            6'd19: glyph = 64'h4040404040407C00;   // 'L'
            6'd23: glyph = 64'h4464544C44444400;   // 'N'
            6'd24: glyph = 64'h3844444444443800;   // 'O'
            6'd25: glyph = 64'h7844447840404000;   // 'P'
            6'd27: glyph = 64'h7844447848444400;   // 'R'
