            6'd37: glyph = 64'h0000000000000000;   // ' '
            6'd38: glyph = 64'h0018180018180000;   // ':'
            6'd39: glyph = 64'h0000000000181800;   // '.'
            6'd40: glyph = 64'h0000007C00000000;   // '-'
            default: glyph = 64'h0000_0000_0000_0000;
        endcase
    end

    // row=0 取最高字节(用 case 显式选择, 兼容性最好)
    reg [7:0] bits_r;
    always @(*) begin
        case (row)
            3'd0: bits_r = glyph[63:56];
            3'd1: bits_r = glyph[55:48];
            3'd2: bits_r = glyph[47:40];
            3'd3: bits_r = glyph[39:32];
            3'd4: bits_r = glyph[31:24];
            3'd5: bits_r = glyph[23:16];
            3'd6: bits_r = glyph[15:8];
            default: bits_r = glyph[7:0];
        endcase
    end
//------------------------------------------------------------------
// [取行] row=0 取最高字节（第 0 行），row=7 取最低字节（最后一行）。
// 之所以用 case 而不是 glyph[(7-row)*8 +: 8]，是为了兼容性最好——
// 某些综合器对“变量下标的部分选择”支持不好，写成 case 最稳妥。
// 上层用法：给出字符码 ch 和行号 row，下一拍（组合逻辑是当拍）得到 8 个点的亮灭。
//------------------------------------------------------------------
    assign bits = bits_r;

endmodule
