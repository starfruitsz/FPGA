//==============================================================================
// 文件: seg.v            模块: seg            实例名: seg_inst(adda 顶层)
// 功能: 4~6 位数码管动态扫描显示。把 10bit AD 码值经 bcd 转成 BCD 码后,
//       按'负号/空白 + 百位 + 十位 + 个位'的组合显示, 并支持小数点。
// 扫描: 1ms 时间基准(CNT_MAX=23999, 50MHz 下 0.48ms/位) -> 6 位一轮,
//       刷新率约 347Hz, 人眼无闪烁。
//==============================================================================
module seg 
#( 
//------------------------------------------------------------------------------
// 参数: 位扫描间隔计数上限, 23999+1 = 24000 个时钟 = 0.48ms
// (原注释写 1ms, 对应 25MHz 时钟; 本工程 50MHz, 实际 0.48ms)
//------------------------------------------------------------------------------
    parameter CNT_MAX=16'd23999 
)
 
( 
    input wire clk, 
    input wire rst_n, 
    input wire [3:0]point, 
    input wire [9:0]data, //？位宽 
    input wire seg_en, 
    input wire sign, 
    
    output reg [3:0]sel, 
    output reg [7:0]seg  
); 
 
//------------------------------------------------------------------------------
// BCD 转换结果: unit 个位, ten 十位, hun 百位(0~9)
//------------------------------------------------------------------------------
wire [3:0]unit; 
wire [3:0]ten; 
wire [3:0]hun; 
  
//------------------------------------------------------------------------------
// [例化] bcd_8421: 10bit 二进制 -> 3 位 BCD(移位加 3 法, 约 22 拍完成)
// 注意: 10bit 最大 1023, 而 3 位 BCD 只能表示 999, 千位溢出会被丢弃,
//       因此 AD 满码附近(>=1000)显示会回绕(如 1020 显示为 020)。
//------------------------------------------------------------------------------
bcd bcd_8421( 
    .clk(clk), 
    .rst_n(rst_n), 
    .data(data), 
    
    .unit(unit), 
    .ten(ten), 
    .hun(hun) 
 ); 
 
//------------------------------------------------------------------------------
// 内部寄存器
//   data_reg : 4 个 4bit 的待显示数字(每位一个 BCD/控制码)
//              取值 0~9 为数字, 10=负号, 11=空白
//   cnt_1ms  : 位扫描时间计数器
//   flag_1ms : 位切换(单周期)脉冲
//   cnt_sel  : 当前扫描位序号 0~5
//   sel_reg  : 6bit 循环移位的一热码, 经取反后作为位选
//   data_disp: 当前位要显示的数字
//   dot_disp : 当前位的小数点
//------------------------------------------------------------------------------
reg [15:0]data_reg; 
reg [15:0]cnt_1ms; 
reg flag_1ms; 
reg [2:0]cnt_sel; 
reg [5:0]sel_reg; 
reg [3:0]data_disp; 
reg dot_disp; 
 
//------------------------------------------------------------------------------
// [块 1] 显示内容组装(4 个 nibble)
//   规则: 高位为 0(不含前导零)则压缩显示位数, 负号占用最左一位。
//   hun!=0 或需显示小数点(point[2]) -> 显示 3 位: {符号,hun,ten,unit}
//   ten!=0 或 point[1]             -> 显示 2 位: {11,符号,ten,unit}
//   unit 或 point[0]               -> 显示 1 位: {11,11,符号,unit}
//   sign=1 时该位填 4'd10(负号), sign=0 时填 4'd11(空白)。
//------------------------------------------------------------------------------
//控制数码管显示 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        data_reg<=1'b0; 
    //若显示的十进制数的百位为非零数据或需显示小数点，则值显示 3 个数码管 
    else if(((hun) || (point[2])) && (sign == 1'b1))//显示负号 
        data_reg <= {4'd10,hun,ten,unit};//4'd10 我们定义为显示负号 
    else if(((hun) || (point[2])) && (sign == 1'b0)) 
        data_reg <= {4'd11,hun,ten,unit}; 
    //若显示的十进制数的十位为非零数据或需显示小数点，则值显示 2 个数码管 
    else if(((ten) || (point[1])) && (sign == 1'b1)) 
        data_reg <= {4'd11,4'd10,ten,unit};
    else if(((ten) || (point[1])) && (sign == 1'b0)) 
        data_reg <= {4'd11,4'd11,ten,unit}; 
    //若显示的十进制数的个位且需显示负号 
    else if(((unit) || (point[0])) && (sign == 1'b1)) 
        data_reg <= {4'd11,4'd11,4'd10,unit}; 
    //若上面都不满足都只显示一位数码管 
    else 
        data_reg <= {4'd11,4'd11,4'd11,unit}; 
 
//------------------------------------------------------------------------------
// [块 2] 位扫描节拍计数器: 0..CNT_MAX 循环, 0.48ms 一轮
//------------------------------------------------------------------------------
//计数器计数 1ms 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        cnt_1ms<=1'b0; 
    else if(cnt_1ms==CNT_MAX) 
        cnt_1ms<=1'b0; 
    else 
        cnt_1ms<=cnt_1ms+1'b1; 
 
//------------------------------------------------------------------------------
// [块 3] 节拍脉冲: cnt_1ms 计满前一拍产生单周期 flag_1ms
//------------------------------------------------------------------------------
//计数标志位 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        flag_1ms<=1'b0; 
    else if(cnt_1ms==CNT_MAX-1'b1) 
        flag_1ms<=1'b1; 
    else 
        flag_1ms<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 4] 位序号: 0->1->2->3->4->5->0 循环, 每 0.48ms 前进一步
//------------------------------------------------------------------------------
//cnt_sel：从 0 到 5 的循环，用于选择当前显示的数码管 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        cnt_sel<=1'b0; 
    else if(cnt_sel==3'b101 && flag_1ms) 
        cnt_sel<=1'b0; 
    else if(flag_1ms) 
        cnt_sel<=cnt_sel+1'b1; 
    else 
        cnt_sel<=cnt_sel; 
 
//------------------------------------------------------------------------------
// [块 5] 位选一热码: cnt_sel=0 时置 1, 之后每拍左移一位
// sel_reg 为 6bit, 对应 6 个数码管; 实际只接 4 位(sel[3:0]), 高 2 位等效于
// 空白时隙, 用于降低平均亮度/消除残影。
//------------------------------------------------------------------------------
//数码管位选信号寄存器 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        sel_reg<=4'b000_000; 
    else if(!cnt_sel && flag_1ms)
        sel_reg<=4'b0001; 
    else if(flag_1ms) 
        sel_reg<=sel_reg<<1; 
    else 
        sel_reg<=sel_reg; 
 
//------------------------------------------------------------------------------
// [块 6] 当前位数字选择(多路选择器)
//   cnt_sel=0 -> data_reg[3:0]  (个位/最右)
//   cnt_sel=1 -> data_reg[7:4]  (十位)
//   cnt_sel=2 -> data_reg[11:8] (百位)
//   cnt_sel=3 -> data_reg[15:12](符号/空白)
//   cnt_sel=4,5 -> 0 (空时隙)
//------------------------------------------------------------------------------
//控制数码管的位选信号，使六个数码管轮流显示 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        data_disp<=1'b0; 
    else if(seg_en && flag_1ms) 
        case(cnt_sel) 
            3'd0:data_disp<=data_reg[3:0]; 
            3'd1:data_disp<=data_reg[7:4]; 
            3'd2:data_disp<=data_reg[11:8]; 
            3'd3:data_disp<=data_reg[15:12]; 
            default:data_disp<=1'b0; 
        endcase 
    else 
        data_disp<=data_disp; 
 
//------------------------------------------------------------------------------
// [块 7] 小数点: 取 point[cnt_sel]
// 说明: point 只有 4bit, 而 cnt_sel 可到 5, 越界时综合为默认(0)。
//------------------------------------------------------------------------------
//dot_disp:小数点也高电平点亮 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        dot_disp<=1'b1; 
    else if(flag_1ms) 
        dot_disp<=point[cnt_sel]; 
    else 
        dot_disp<=dot_disp; 
 
//------------------------------------------------------------------------------
// [块 8] 段选译码(共阴/共阳取决于硬件, 这里是'1 点亮'的段码表)
//   bit7 = 小数点, bit6..0 = g,f,e,d,c,b,a
//   0~9 为标准七段码; 4'd10 -> 8'b0100_0000(只亮中间一横, 作为负号);
//   4'd11 -> 8'b0000_0000(全灭, 空白位)。
//------------------------------------------------------------------------------
//控制数码管段选信号，显示数字 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        seg<=8'b0000_0000; 
    else 
        case(data_disp) 
            4'd0:seg<={dot_disp,7'b0111111}; 
            4'd1:seg<={dot_disp,7'b0000110}; 
            4'd2:seg<={dot_disp,7'b1011011}; 
            4'd3:seg<={dot_disp,7'b1001111}; 
            4'd4:seg<={dot_disp,7'b1100110}; 
            4'd5:seg<={dot_disp,7'b1101101}; 
            4'd6:seg<={dot_disp,7'b1111101}; 
            4'd7:seg<={dot_disp,7'b0000111}; 
            4'd8:seg<={dot_disp,7'b1111111}; 
            4'd9:seg<={dot_disp,7'b1101111}; 
            4'd10:seg<=8'b0100_0000; 
            4'd11:seg<=8'b0000_0000; 
            default:seg<=8'b0011_1111; 
        endcase 
 
//------------------------------------------------------------------------------
// [块 9] 位选输出: sel = ~sel_reg(低电平有效的共阴数码管位选)
// 注意 sel 只有 4bit, 6bit 的 sel_reg 取反后被截断 -> cnt_sel=4/5 时
// sel=4'b1111(全部熄灭), 正好实现两个空时隙, 属'误打误撞'的正确结果。
//------------------------------------------------------------------------------
//sel：数码管位选信号赋值 
always @(posedge clk or negedge rst_n) 
    if(!rst_n) 
        sel<=4'b0_000; 
    else 
        sel<=~sel_reg;
        
//------------------------------------------------------------------------------
// 附注: sel_reg 初值写 6'b000_000, 而 sel 初值 4'b0_000, 复位期间全部熄灭。
//------------------------------------------------------------------------------
endmodule 