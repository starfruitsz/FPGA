//==============================================================================
// 文件: uart_rx.v         模块: uart_rx         实例名: uart_rx_inst(adda 顶层)
// 功能: 标准 UART 接收器(8 数据位、1 停止位、无校验), 位宽 8bit。
// 参数: UART_BPS=115200, CLK_FREQ=50_000_000
//       位周期计数值 BAUD_CNT_MAX = 50e6/115200 = 434 (实际波特率 115207, 误差 0.006%)
// 时序: 1) 3 级同步器消除亚稳态;
//       2) 检测 rx 下降沿作为起始位;
//       3) 在每个位周期的中点(第 216 拍)采样, 抗边沿抖动;
//       4) 第 8 位采完后输出 1 拍 po_flag。
//==============================================================================
module uart_rx 
#( 
//------------------------------------------------------------------------------
// 参数: 波特率与系统时钟频率(顶层例化时覆盖为 115200 / 50MHz)
//------------------------------------------------------------------------------
    parameter UART_BPS ='d115200,         //波特率9600
    parameter CLK_FREQ ='d50_000_000    //50MHz
)
 
( 
    input wire sys_clk, 
    input wire sys_rst_n, 
    input wire rx, 
    
    output reg [7:0] po_data, 
    output reg po_flag 
); 

//------------------------------------------------------------------------------
// 派生参数: 每位对应的系统时钟数 = 50MHz/115200 = 434
//------------------------------------------------------------------------------
parameter BAUD_CNT_MAX =CLK_FREQ/UART_BPS;      //计数周期最大值=频率/波特率

//------------------------------------------------------------------------------
// 内部信号
//   rx_reg1..3 : 三级同步寄存(异步输入 rx -> 系统时钟域)
//   start_flag : 起始位检测脉冲(单周期)
//   work_en    : 接收忙标志(1=正在接收一帧)
//   baud_cnt   : 位内计数 0..433
//   bit_flag   : 位中点采样脉冲(单周期)
//   bit_cnt    : 位计数 0..8(0=起始位, 1~8=数据位)
//   rx_data    : 移位接收缓冲(LSB 先到)
//   rx_flag    : 一帧接收完成脉冲
//------------------------------------------------------------------------------
reg rx_reg1; 
reg rx_reg2; 
reg rx_reg3; 
reg start_flag; 
reg work_en; 
reg[15:0]baud_cnt; 
reg bit_flag; 
reg[4:0] bit_cnt; 
reg[7:0] rx_data; 
reg rx_flag; 
    
//------------------------------------------------------------------------------
// [块 1] 同步器第 1 级: 直接寄存异步的 rx 引脚
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        rx_reg1<=1'b1; 
    else
        rx_reg1<=rx; 
 
//------------------------------------------------------------------------------
// [块 2] 同步器第 2 级
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        rx_reg2<=1'b1; 
    else 
        rx_reg2<=rx_reg1; 
 
//------------------------------------------------------------------------------
// [块 3] 同步器第 3 级: rx_reg3 为'滤波后'的稳定电平, 供采样使用
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        rx_reg3<=1'b1; 
    else 
        rx_reg3<=rx_reg2; 
 
//------------------------------------------------------------------------------
// [块 4] 起始位检测: rx_reg3=1(前一拍高) 且 rx_reg2=0(本拍低) 且空闲,
// 产生单周期 start_flag。用 rx_reg2 判断下降了沿是为了再打一拍、避开亚稳态。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        start_flag<=1'b0; 
    else if((rx_reg3==1'b1)&&(rx_reg2==1'b0)&&(work_en==1'b0)) 
        start_flag<=1'b1; 
    else 
        start_flag<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 5] 接收忙标志: 检出起始位后置 1, 收满 8 个数据位(bit_cnt=8)后清 0。
// 该标志同时给 baud_cnt 做清零使能, 保证空闲时计数器归零。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        work_en<=1'b0; 
    else if(start_flag==1'b1) 
        work_en<=1'b1; 
    else if ((bit_cnt==5'd8)&&(bit_flag==1'b1)) 
        work_en<=1'b0; 
    else 
        work_en<=work_en; 
 
//------------------------------------------------------------------------------
// [块 6] 位内计数: work_en=0 或计满时清零, 否则 +1
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        baud_cnt<=16'd0; 
    else if((baud_cnt==BAUD_CNT_MAX-1)||(work_en==1'b0)) 
        baud_cnt<=16'd0; 
    else 
        baud_cnt<=baud_cnt+16'd1; 

//------------------------------------------------------------------------------
// [块 7] 位中点采样脉冲: 计到 BAUD_CNT_MAX/2-1 = 216 时产生,
// 即每个位的中间时刻, 是对 UART 允许 ±2% 时钟偏差的经典处理。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        bit_flag<=1'b0; 
    else if(baud_cnt==BAUD_CNT_MAX/2-1) 
        bit_flag<=1'b1; 
    else 
        bit_flag<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 8] 位计数: 0 为起始位, 1~8 为 8 个数据位, 计满 8 后回 0
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        bit_cnt<=5'b0; 
    else if((bit_cnt==5'd8)&&(bit_flag==1'b1)) 
        bit_cnt<=5'b0; 
    else if(bit_flag==1'b1) 
        bit_cnt<=bit_cnt+1'b1; 
 
//------------------------------------------------------------------------------
// [块 9] 数据移位: bit_cnt 1~8 的中点各采样一次, LSB 在前(右移拼接)
//   rx_data <= {rx_reg3, rx_data[7:1]}  => 先到的位落在 bit0。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        rx_data<=8'b0; 
    else if(( bit_cnt<=5'd8)&&(bit_cnt>=5'd1)&&(bit_flag==1'b1)) 
        rx_data<={rx_reg3,rx_data[7:1]}; 
 
//------------------------------------------------------------------------------
// [块 10] 完成脉冲: 第 8 位采样时刻置 rx_flag(单周期)
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        rx_flag<=1'b0; 
    else if((bit_cnt==5'd8)&&(bit_flag==1'b1)) 
        rx_flag<=1'b1; 
    else 
        rx_flag<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 11] 输出数据锁存(仅在 rx_flag 时更新, 保证数据稳定 1 个位周期以上)
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        po_data<=8'b0; 
    else if(rx_flag==1'b1) 
        po_data<=rx_data; 
 
//------------------------------------------------------------------------------
// [块 12] 输出标志打一拍, 使 po_flag 与 po_data 同拍有效
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        po_flag<=1'b0; 
    else 
        po_flag<=rx_flag; 
        
//------------------------------------------------------------------------------
// 附注: 本模块不检测帧错误与溢出(无 stop bit 校验), 连续高速收发时若上位机
// 发送过快可能丢字节, 已有实现对本工程(指令帧偶发)足够。
//------------------------------------------------------------------------------
endmodule
 