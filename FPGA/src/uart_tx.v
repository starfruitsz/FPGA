//==============================================================================
// 文件: uart_tx.v         模块: uart_tx         实例名: uart_tx_inst(adda 顶层)
// 功能: 标准 UART 发送器, 一次发送 16bit(拆成两帧 8N1 连续发出)。
// 帧结构(共 21 个位时隙):
//   0      : 起始位 0
//   1 ~ 8  : 第 1 字节 data[7:0](LSB 先发), 9~10: 两个停止位
//   11     : 第 2 帧起始位 0
//   12 ~ 19: 第 2 字节 data[15:8], 20: 停止位
// 参数: UART_BPS=115200, CLK_FREQ=50MHz -> 每位 434 个时钟
// 特点: pi_flag 常为 1 时发送器自由连续发送(本工程就是这样用的)。
//==============================================================================
module uart_tx 
#( 
//------------------------------------------------------------------------------
// 参数: 波特率与系统时钟(顶层覆盖为 115200 / 50MHz)
//------------------------------------------------------------------------------
    parameter UART_BPS ='d115200, 
    parameter CLK_FREQ ='d50_000_000 
)
 
( 
    input wire sys_clk, 
    input wire sys_rst_n, 
    input wire[15:0] pi_data, 
    input wire pi_flag, 
 
    output reg tx 
); 
    
//------------------------------------------------------------------------------
// 派生参数: 每位 434 个系统时钟
//------------------------------------------------------------------------------
parameter BAUD_CNT_MAX =CLK_FREQ/UART_BPS; 
 
//------------------------------------------------------------------------------
// 内部信号
//   work_en : 发送忙标志
//   baud_cnt: 位内计数 0..(BAUD_CNT_MAX-1)
//   bit_flag: 位起始脉冲(每个位周期产生一次)
//   bit_cnt : 位序号 0..20
//------------------------------------------------------------------------------
reg work_en; 
reg [15:0] baud_cnt; 
reg bit_flag; 
reg [4:0] bit_cnt; 
 
//------------------------------------------------------------------------------
// [块 1] 忙标志: pi_flag 到来即启动; 发完第 20 个时隙(停止位)后自动结束。
// 由于 pi_flag 在 adda 中恒为 1, 结束当拍又会被置 1, 形成连续发送。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        work_en<=1'b0; 
    else if(pi_flag==1'b1) 
        work_en<=1'b1; 
    else if((bit_cnt==5'd20)&&(bit_flag==1'b1)) 
        work_en<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 2] 位内计数: 空闲清零; 忙时 0..433 循环
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        baud_cnt<=16'd0; 
    else if((work_en==1'b0)||(baud_cnt==BAUD_CNT_MAX-1)) 
        baud_cnt<=16'd0; 
    else if(work_en==1'b1) 
        baud_cnt<=baud_cnt+16'd1; 
 
//------------------------------------------------------------------------------
// [块 3] 位起始脉冲: baud_cnt=1 时置 1,
// 即每一位的第一个时钟产生 bit_flag, tx 在此时切换到下一个位的电平。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        bit_flag<=1'b0;
    else if(baud_cnt==16'd1) 
        bit_flag<=1'b1; 
    else 
        bit_flag<=1'b0; 
 
//------------------------------------------------------------------------------
// [块 4] 位序号: 0..20 循环, 每来一个位脉冲 +1
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        bit_cnt<=5'd0; 
    else if((bit_cnt==5'd20)&&(bit_flag==1'b1)) 
        bit_cnt<=5'd0; 
    else if((bit_flag==1'b1)&&(work_en==1'b1)) 
        bit_cnt<=bit_cnt+5'd1; 
 
//------------------------------------------------------------------------------
// [块 5] 发送移位输出(状态机式的 case 查表)
//   时隙 0      : 0           起始位
//   时隙 1~8    : pi_data[0..7]
//   时隙 9,10   : 1           停止位(第 1 帧结束, 留 2 位空闲)
//   时隙 11     : 0           第 2 帧起始位
//   时隙 12~19  : pi_data[8..15]
//   时隙 20     : 1           停止位
// 复位空闲时 tx=1(UART 空闲电平)。
//------------------------------------------------------------------------------
always@(posedge sys_clk or negedge sys_rst_n) 
    if(sys_rst_n==1'b0) 
        tx<=1'b1; 
    else if(bit_flag==1'b1) 
        case(bit_cnt) 
            0:tx<=1'b0; 
            1:tx<=pi_data[0]; 
            2:tx<=pi_data[1]; 
            3:tx<=pi_data[2]; 
            4:tx<=pi_data[3]; 
            5:tx<=pi_data[4]; 
            6:tx<=pi_data[5]; 
            7:tx<=pi_data[6]; 
            8:tx<=pi_data[7]; 
            9:tx<=1'b1; 
            10:tx<=1'b1; 
            11:tx<=1'b0; 
            12:tx<=pi_data[8]; 
            13:tx<=pi_data[9]; 
            14:tx<=pi_data[10]; 
            15:tx<=pi_data[11]; 
            16:tx<=pi_data[12]; 
            17:tx<=pi_data[13]; 
            18:tx<=pi_data[14]; 
            19:tx<=pi_data[15]; 
            20:tx<=1'b1; 
            default:tx<=1'b1; 
        endcase 
 
//------------------------------------------------------------------------------
// 附注: 20 个位时隙 = 2.08ms/帧(115200bps), 上位机按 16bit 小端解析即可还原
// adda 中拼接的 {ad_date[7:0], 6'h0, ad_date[9:8]}。
//------------------------------------------------------------------------------
endmodule 